/** Offsets in km east (dx) and north (dy) of the town square. */
function at(dxKm: number, dyKm: number): { latitude: number; longitude: number } {
  const lat = DEMO_CENTER.latitude + dyKm / 111.0;
  const lng = DEMO_CENTER.longitude + dxKm / (111.0 * Math.cos((DEMO_CENTER.latitude * Math.PI) / 180));
  return { latitude: Number(lat.toFixed(5)), longitude: Number(lng.toFixed(5)) };
}

/** Local wall-clock time `days` from today at hh:mm, as an ISO instant. */
function localTime(now: Date, days: number, hour: number, minute = 0): string {
  const d = new Date(now.getFullYear(), now.getMonth(), now.getDate() + days, hour, minute, 0, 0);
  return d.toISOString();
}

/** Same as localTime, but guarantees the time is still ahead of `now` (rolls to tomorrow). */
function upcomingToday(now: Date, hour: number, minute = 0): string {
  const today = new Date(now.getFullYear(), now.getMonth(), now.getDate(), hour, minute);
  return (today.getTime() > now.getTime() ? today : new Date(today.getTime() + 86_400_000)).toISOString();
}

